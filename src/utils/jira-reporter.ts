import type { Reporter, TestCase, TestResult } from '@playwright/test/reporter';

export default class JiraReporter implements Reporter {
    async onTestEnd(test: TestCase, result: TestResult) {
        if (result.status === 'failed') {
            console.log(`\n[Jira Reporter] Test failed: ${test.title}. Creating Jira issue...`);

            if (!process.env.JIRA_API_TOKEN) {
                console.warn('[Jira Reporter] Missing JIRA_API_TOKEN. Skipping Jira integration.');
                return;
            }

            const url = `https://${process.env.JIRA_DOMAIN}/rest/api/2/issue`;
            const auth = Buffer.from(`${process.env.JIRA_EMAIL}:${process.env.JIRA_API_TOKEN}`).toString('base64');

            const payload = {
                fields: {
                    project: { key: process.env.JIRA_PROJECT_KEY },
                    summary: `E2E Test Failed: ${test.title}`,
                    description: `Automated bug report generated by Playwright.\n\n*File:* ${test.location.file}\n*Error Log:* \n{code}\n${result.error?.message || 'No details provided'}\n{code}`,
                    issuetype: { name: 'Błąd' }
                }
            };

            try {
                const response = await fetch(url, {
                    method: 'POST',
                    headers: {
                        'Authorization': `Basic ${auth}`,
                        'Content-Type': 'application/json',
                    },
                    body: JSON.stringify(payload),
                });

                if (response.ok) {
                    const data = await response.json();
                    console.log(`[Jira Reporter] Successfully created Jira issue. Ticket: ${data.key}`);
                } else {
                    console.error('[Jira Reporter] Failed to create Jira issue:', await response.text());
                }
            } catch (error) {
                console.error('[Jira Reporter] Network error while connecting to Jira:', error);
            }
        }
    }
}